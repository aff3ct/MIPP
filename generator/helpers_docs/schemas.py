"""
Registry reference of the MIPP generator.

Renders the JSON Schemas of `generator/helpers_headers/schemas/` and
`generator/helpers_tests/schemas/` into the Markdown pages of
`docs/developer/reference/registries/`: one page per schema, with the files it
validates, its description, an example and a table of the fields.

Annotations used (all standard JSON Schema, ignored by the validation):
- `title`: page title; `description`: Markdown text (page introduction, or field
  description in the tables);
- `examples`: the first example is shown as a JSON block;
- `propertyNames.title`: name of the keys of a map (`<function>`), in the field paths.
"""
import json
import os

# Page order, schema, files validated by the schema (relative to generator/), code fence language
PAGES = [
    ("interfaces", "helpers_headers/schemas/interfaces_schema.json",
     ["helpers_headers/registry_interfaces.json"], "json"),
    ("protos", "helpers_headers/schemas/protos_schema.json",
     ["helpers_headers/registry_protos.json"], "json"),
    ("categories", "helpers_headers/schemas/categories_schema.json",
     ["helpers_headers/registry_categories.json"], "json"),
    ("scalar_implems", "helpers_headers/schemas/scalar_implems_schema.json",
     ["helpers_headers/registry_scalar_implems.json"], "mipp-json"),
    ("isa", "helpers_headers/schemas/isa_schema.json",
     ["simd_ext/<isa>/<isa>_isa.json", "helpers_headers/registry_scalar_isa.json"], "json"),
    ("implems", "helpers_headers/schemas/implems_schema.json",
     ["simd_ext/<isa>/<isa>_native_implems.json", "simd_ext/<isa>/<isa>_emu_implems.json",
      "helpers_headers/generic_emu_implems.json", "helpers_headers/generic_emu_implems_mask.json",
      "helpers_headers/generic_emu_implems_lmulh.json"], "json"),
    ("templates", "helpers_headers/schemas/templates_schema.json",
     ["simd_ext/<isa>/<isa>_native_templates.json", "simd_ext/<isa>/<isa>_emu_templates.json",
      "helpers_headers/generic_emu_templates.json", "helpers_headers/generic_emu_templates_mask.json",
      "helpers_headers/generic_emu_templates_lmulh.json"], "mipp-json"),
    ("explorer_isa", "helpers_headers/schemas/explorer_isa_schema.json",
     ["simd_ext/<isa>/<isa>_explorer.json"], "json"),
    ("tests_specs", "helpers_tests/schemas/specs_schema.json",
     ["helpers_tests/tests_specs.json"], "json"),
    ("tests_templates", "helpers_tests/schemas/templates_schema.json",
     ["helpers_tests/tests_templates.json"], "json"),
]

# JSON files of generator/ without a schema
UNVALIDATED = [
    ("helpers_headers/funcs_docs.json",
     "Description and LaTeX formula of each function, for the Function Support pages and the API Explorer."),
    ("helpers_headers/jinja_keywords.json",
     "Jinja2 keywords ignored when the dependencies of a template are extracted from its `%...%` markers."),
]

GENERATED_NOTE = [
    '!!! info "Generated page"',
    "    This page is generated by `gen_mipp_docs.py` from the JSON Schemas of the generator "
    "(`generator/helpers_headers/schemas/`, `generator/helpers_tests/schemas/`). To change it, edit the "
    "`description` fields of the schemas, not this page.",
    "",
]


def _cell(text):
    return " ".join((text or "").split()).replace("|", "\\|")


def _def_anchor(name):
    return f"def-{name}"


def _type_str(s):
    if not isinstance(s, dict):
        return "any"
    if "$ref" in s:
        name = s["$ref"].split("/")[-1]
        return f"[`{name}`](#{_def_anchor(name)})"
    if "const" in s:
        return f"`{json.dumps(s['const'])}`"
    alts = s.get("anyOf") or s.get("oneOf")
    if alts and "type" not in s:
        out = []
        for a in alts:
            t = _type_str(a)
            if t not in out:
                out.append(t)
        return " or ".join(out)
    t = s.get("type")
    if t is None:
        return "any"
    if isinstance(t, list):
        return " or ".join(t)
    if t == "array":
        items = s.get("items")
        return f"array of {_type_str(items)}" if isinstance(items, dict) else "array"
    if t == "object":
        ap = s.get("additionalProperties")
        if isinstance(ap, dict) and not s.get("properties"):
            return f"map of {_type_str(ap)}"
        return "object"
    return t


def _has_children(s):
    if not isinstance(s, dict) or "$ref" in s:
        return False
    if s.get("properties") or isinstance(s.get("additionalProperties"), dict):
        return True
    if isinstance(s.get("items"), dict) and _has_children(s["items"]):
        return True
    return any(_has_children(a) for a in (s.get("anyOf") or s.get("oneOf") or []))


def _desc(s, required):
    parts = []
    if required:
        parts.append("**Required.**")
    if s.get("description"):
        parts.append(s["description"])
    if "enum" in s:
        parts.append("Values: " + ", ".join(f"`{json.dumps(v) if not isinstance(v, str) else v}`" for v in s["enum"]) + ".")
    if "default" in s:
        parts.append(f"Default: `{json.dumps(s['default'])}`.")
    return _cell(" ".join(parts))


def _rows(s, path, required, rows):
    """Flattens a schema node into (path, type, description) rows. $ref targets are not
    expanded: they are rendered in the Definitions section."""
    rows.append((path, _type_str(s), _desc(s, required)))
    _child_rows(s, path, rows)


def _join(base, name):
    return f"{base}.{name}" if base else name


def _child_rows(s, base, rows):
    if not isinstance(s, dict) or "$ref" in s:
        return
    req = set(s.get("required", []))
    for name, sub in (s.get("properties") or {}).items():
        _rows(sub, _join(base, name), name in req, rows)
    ap = s.get("additionalProperties")
    if isinstance(ap, dict):
        key = (s.get("propertyNames") or {}).get("title", "key")
        _rows(ap, _join(base, f"<{key}>"), False, rows)
    items = s.get("items")
    if isinstance(items, dict) and _has_children(items):
        _child_rows(items, f"{base}[]", rows)
    for alt in s.get("anyOf") or s.get("oneOf") or []:
        if _has_children(alt):
            _child_rows(alt, base, rows)


def _table(rows):
    lines = ["| Field | Type | Description |", "| :--- | :--- | :--- |"]
    for path, typ, desc in rows:
        field = f"`{path}`" if path else "*(root)*"
        lines.append(f"| {field} | {typ} | {desc} |")
    return "\n".join(lines)


def render_schema_page(schema, files, lang):
    title = schema.get("title", "Registry")
    md = [f"# {title}", ""] + GENERATED_NOTE
    if schema.get("description"):
        md += [schema["description"].strip(), ""]
    md += ["| Files (in `generator/`) | Schema |", "| :--- | :--- |"]
    md.append(f"| {'<br>'.join(f'`{f}`' for f in files)} | `{schema['_path']}` |")
    md.append("")
    examples = schema.get("examples")
    if examples:
        md += ["## Example", "", f"```{lang}", json.dumps(examples[0], indent=4, ensure_ascii=False), "```", ""]

    rows = []
    _child_rows(schema, "", rows)
    if rows:
        md += ["## Fields", "", _table(rows), ""]

    defs = schema.get("definitions") or {}
    if defs:
        md += ["## Definitions", ""]
        for name, d in defs.items():
            md += [f"### `{name}` {{ #{_def_anchor(name)} }}", ""]
            md += [f"*Type:* {_type_str(d)}. {_desc(d, False)}".rstrip(), ""]
            rows = []
            _child_rows(d, "", rows)
            if rows:
                md += [_table(rows), ""]
    return "\n".join(md).rstrip() + "\n"


def render_index(entries):
    md = ["# Registries", ""] + GENERATED_NOTE
    md += [
        "The generator reads its inputs from JSON files of `generator/`. Each file is validated against a "
        "JSON Schema when it is loaded: a validation error stops the generator (see "
        "[Static Audits](../audits.md)). The schemas are documented in the pages of this section.",
        "",
        "| Page | Files (in `generator/`) |",
        "| :--- | :--- |",
    ]
    for slug, title, files in entries:
        md.append(f"| [{title}]({slug}.md) | {'<br>'.join(f'`{f}`' for f in files)} |")
    md += ["", "Files without a schema:", ""]
    md += [f"- `{f}`: {d}" for f, d in UNVALIDATED]
    return "\n".join(md) + "\n"


def write_registries_reference(generator_dir, out_dir):
    """Writes out_dir/{index.md, <page>.md, .pages}. Returns the list of written files."""
    os.makedirs(out_dir, exist_ok=True)
    written = []
    entries = []
    for slug, schema_rel, files, lang in PAGES:
        with open(os.path.join(generator_dir, schema_rel), encoding="utf-8") as f:
            schema = json.load(f)
        schema["_path"] = schema_rel
        title = schema.get("title", slug)
        entries.append((slug, title, files))
        path = os.path.join(out_dir, f"{slug}.md")
        with open(path, "w", encoding="utf-8") as f:
            f.write(render_schema_page(schema, files, lang))
        written.append(path)

    path = os.path.join(out_dir, "index.md")
    with open(path, "w", encoding="utf-8") as f:
        f.write(render_index(entries))
    written.append(path)

    path = os.path.join(out_dir, ".pages")
    with open(path, "w", encoding="utf-8") as f:
        f.write("title: Registries\nnav:\n  - Overview: index.md\n")
        for slug, title, _ in entries:
            f.write(f"  - {title}: {slug}.md\n")
    written.append(path)
    return written
