"""
Markdown fragments generated for the hand-written pages of the documentation.

Tables that restate the registries and the ISA descriptors are generated here, so
that they cannot drift from the generator. They are written to
`docs/includes/generated/` (ignored by Git, excluded from the site by
`exclude_docs`) and included in the pages with pymdownx.snippets:

    --8<-- "docs/includes/generated/<name>.md"

The fragments contain no links: they are included in pages at different depths.
"""
import json
import os

from datatypes import all_datatypes, all_ldiv, all_lmul
from registry import MASK_SUPPORT_MAP, categories, interfaces

# Display name of the targets, and order of the rows (other ISAs are appended)
TARGET_NAMES = {
    "sse": "SSE",
    "avx": "AVX / AVX2",
    "avx512": "AVX-512",
    "neon": "NEON",
    "sve": "SVE",
    "rvv": "RVV",
    "scalar": "Scalar",
}

# C++ name of the scalar types that have one (the others are the <stdint.h> names)
CXX_SCALAR_NAMES = {"float64_t": "double", "float32_t": "float"}


def _header(source):
    return f"<!-- Generated by generator/gen_mipp_docs.py --only includes, from {source}. Do not edit. -->\n\n"


def _load_isas(generator_dir):
    """ISA descriptors (simd_ext/<isa>/<isa>_isa.json and registry_scalar_isa.json), in display order."""
    isas = {}
    ext_dir = os.path.join(generator_dir, "simd_ext")
    for name in sorted(os.listdir(ext_dir)):
        path = os.path.join(ext_dir, name, f"{name}_isa.json")
        if os.path.isfile(path):
            with open(path, "r", encoding="utf-8") as f:
                isas[name] = json.load(f)
    with open(os.path.join(generator_dir, "helpers_headers", "registry_scalar_isa.json"), "r", encoding="utf-8") as f:
        isas["scalar"] = json.load(f)
    order = [n for n in TARGET_NAMES if n in isas] + sorted(n for n in isas if n not in TARGET_NAMES)
    return [(n, isas[n]) for n in order]


def _width(isa):
    size = isa.get("size")
    if isa.get("is_scalar"):
        return "`MIPP_SCALAR_SIZE`"
    if isinstance(size, int):
        return f"{size} bits"
    if isinstance(size, list):
        return f"{min(size)} to {max(size)} bits, fixed at compile time"
    return "`VLEN`, fixed at compile time"


def _lmul_cell(isa, lmul):
    """How a register of the given LMUL (-2 for d2) is represented on the target."""
    if isa.get("is_scalar"):
        # The scalar generator (simd_ext/scalar/scalar_gen.py) emits every LMUL of all_lmul
        # and the d2 types, as arrays, whatever its descriptor declares.
        return "array" if lmul in all_lmul or -lmul in all_ldiv else "—"
    if lmul in isa.get("hw_lmul", []):
        return {1: "native"}.get(lmul, "native group" if lmul > 1 else "native fractional")
    if lmul in isa.get("sw_lmul", []):
        if lmul == 1:
            return "native"
        if lmul > 1:
            return "struct"
        if isa.get("sw_ldiv_type") == "mask":
            return "half of an LMUL = 1 register"
        if isa.get("sw_ldiv_type") == "sub_isa" and isa.get("sub_isa"):
            return f"{isa['sub_isa'].upper()} register"
        return "struct"
    return "—"


def render_lmul_availability(generator_dir):
    lmuls = list(all_lmul) + [-d for d in all_ldiv]
    head = ["Target", "Register width"] + [f"LMUL = {l}" for l in all_lmul] + [f"`d{d}`" for d in all_ldiv]
    head.append("`MIPP_LDIV_2`")
    lines = ["| " + " | ".join(head) + " |", "| " + " | ".join([":---"] * 2 + [":---:"] * (len(head) - 2)) + " |"]
    for name, isa in _load_isas(generator_dir):
        # Same condition as the definition of MIPP_LDIV_2 (helpers_headers/ci_generator.py)
        has_ldiv2 = isa.get("is_scalar", False) or (-2 in isa.get("hw_lmul", [])) or (-2 in isa.get("sw_lmul", []))
        row = [f"**{TARGET_NAMES.get(name, name)}**", _width(isa)]
        row += [_lmul_cell(isa, l) for l in lmuls]
        row.append("defined" if has_ldiv2 else "—")
        lines.append("| " + " | ".join(row) + " |")
    legend = (
        "\n*native*: one hardware register; *native group* / *native fractional*: hardware register group or "
        "fractional register type; *struct*: structure of LMUL=1 registers; *SSE register* / *AVX register*: "
        "register of the narrower ISA; *half of an LMUL = 1 register*: same register as LMUL = 1, only the lower "
        "half of the lanes is meaningful; *array*: plain array of elements; —: not generated.\n"
    )
    return _header("simd_ext/<isa>/<isa>_isa.json (sw_lmul, hw_lmul, sw_ldiv_type)") + "\n".join(lines) + "\n" + legend


def render_datatypes(generator_dir):
    with open(os.path.join(generator_dir, "helpers_headers", "registry_scalar_isa.json"), "r", encoding="utf-8") as f:
        scalar_types = json.load(f)["datatypes"]
    lines = [
        "| MIPP Datatype | Scalar Type (`T`) | C Vector Type (`LMUL=1`) | C Mask Type (`LMUL=1`) |",
        "| :--- | :--- | :--- | :--- |",
    ]
    for dt in all_datatypes:
        reg = scalar_types[dt]["reg"]
        scalar = f"`{CXX_SCALAR_NAMES[reg]}` / `{reg}`" if reg in CXX_SCALAR_NAMES else f"`{reg}`"
        lines.append(f"| `{dt}` | {scalar} | `rvd_{dt}_t` | `rvm_{dt}_t` |")
    return _header("helpers_headers/datatypes.py and registry_scalar_isa.json") + "\n".join(lines) + "\n"


def render_categories():
    lines = ["| Category | Functions |", "| :--- | :--- |"]
    for cat in sorted(categories):
        funcs = sorted(categories[cat])
        lines.append(f"| `{cat}` ({len(funcs)}) | " + ", ".join(f"`{fn}`" for fn in funcs) + " |")
    return _header("helpers_headers/registry_categories.json") + "\n".join(lines) + "\n"


def render_mask_support():
    def yes(flag):
        return "yes" if flag else "—"

    lines = [
        "| `mask_support` | Merge-Masked (`mask`) | Zero-Masked (`maskz`) | Source-Masked (`masks`) | Functions |",
        "| :--- | :---: | :---: | :---: | :---: |",
    ]
    for value, support in MASK_SUPPORT_MAP.items():
        n_funcs = sum(1 for itf in interfaces.values() if itf["mask_support"] is support)
        lines.append(f"| `{value}` | {yes(support.is_maskable())} | {yes(support.is_maskzable())} | "
                     f"{yes(support.is_masksable())} | {n_funcs} |")
    return _header("MASK_SUPPORT_MAP (helpers_headers/registry.py) and registry_interfaces.json") + "\n".join(lines) + "\n"


def write_includes(generator_dir, out_dir):
    """Writes the fragments into out_dir (deleted and rewritten)."""
    os.makedirs(out_dir, exist_ok=True)
    for old in os.listdir(out_dir):
        if old.endswith(".md"):
            os.remove(os.path.join(out_dir, old))
    fragments = {
        "lmul_availability.md": render_lmul_availability(generator_dir),
        "datatypes.md": render_datatypes(generator_dir),
        "categories.md": render_categories(),
        "mask_support.md": render_mask_support(),
    }
    for name, text in fragments.items():
        with open(os.path.join(out_dir, name), "w", encoding="utf-8") as f:
            f.write(text)
